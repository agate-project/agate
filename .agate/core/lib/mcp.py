def cmd_extension(root: Path, action: str) -> int:
    state = px.status(root, "mcp")
    rel = ".agate/project/mcp.py"
    if action == "status":
        print({"absent": f"No {rel} in this project.",
               "approved": f"{rel}: approved.",
               "own": f"{rel}: changed by you; it is approved automatically on the next run.",
               "unapproved": f"{rel}: changed by someone else and NOT approved. `agate.py mcp extension review`."}[state])
        return 0
    if state == "absent":
        print(f"No {rel} in this project.")
        return 0
    if action == "review":
        print(px.review(root, "mcp"))
        return 0
    if action == "approve":
        px.approve(root, "mcp", how="manual")
        print(f"{rel} approved on this machine. Run `agate.py mcp sync` to apply it.")
        return 0
    return 1


def cmd_add(root: Path, a) -> int:
    if not NAME_RE.match(a.name):
        die("The name must use lowercase letters, numbers, - or _ (e.g. clickup).")
    data = read_json(root / SERVERS_REL, {"servers": {}})
    servers = data.setdefault("servers", {})
    if a.name in servers and not a.force:
        die(f"'{a.name}' already exists in servers.json (use --force to replace it).")
    env = list(dict.fromkeys(a.env or []))
    for var in env:
        if not VAR_RE.match(var):
            die(f"'{var}' does not look like a variable name (UPPER_SNAKE_CASE). Names go here, not values.")
    if a.type == "local":
        if not a.command:
            die("A local connector needs --command.")
        server = {"type": "local", "command": a.command, "args": list(a.args or [])}
    else:
        if not a.url:
            die("A remote connector needs --url.")
        server = {"type": "remote", "url": a.url}
        if a.auth == "token" and not (a.token_env or env):
            die("With --auth token, give the token variable name with --env (or --token-env).")
        if a.token_env:
            env = list(dict.fromkeys([a.token_env] + env))
            server["token_env"] = a.token_env
    server.update({"auth": a.auth, "env": env, "docs": a.docs or "", "official": not a.community,
                   "added": _dt.date.today().isoformat(), "by": a.by or ""})
    servers[a.name] = server
    write_json(root / SERVERS_REL, data)

    # Variables are registered by the common `env` module (name + where to get it in .env.example, empty line in .env,
    # owner in .agate/env.json), the same way skills register theirs.
    import env as env_mod  # noqa: PLC0415
    new_vars, local_vars = [], []
    for var in env:
        r = env_mod.add(root, var, a.where or "", a.name, a.docs or "")
        if r["example"]:
            new_vars.append(var)
        if r["local"]:
            local_vars.append(var)

    print(f"Added '{a.name}' to .agate/mcp/servers.json.")
    if new_vars:
        print("Added to .env.example: " + ", ".join(new_vars))
    if local_vars:
        print("Left empty in your .env: " + ", ".join(local_vars) + ". The person sets each one with "
              "`python3 .agate/agate.py env set NAME` (hidden input) or pastes it in .env with the editor.")
    print("Next: `python3 .agate/agate.py mcp sync` and note the connector in .agate/mcp/README.md.")
    return 0


def build_env(server: dict, env: dict[str, str]) -> tuple[dict[str, str], list[str]]:
    """Server environment: the process environment + only the declared variables (from .env)."""
    declared = list(server.get("env", []))
    child = dict(os.environ)
    missing = []
    for var in declared:
        if env.get(var):
            child[var] = env[var]
        else:
            missing.append(var)
    return child, missing


def cmd_run(root: Path, name: str, user: bool) -> int:
    server = get_server(root, name, user)
    env = secrets(root, user)
    child, missing = build_env(server, env)
    if missing:
        die(f"Connector '{name}' is missing values in .env: {', '.join(missing)}. "
            "Paste them into .env (not into the chat) and try again.")
    declared = list(server.get("env", []))
    if server.get("type") == "local":
        cmd = [expand(server["command"], env, declared)] + [expand(x, env, declared) for x in server.get("args", [])]
    else:
        # Remote with a token, seen from a harness without a header helper: stdio→HTTP proxy.
        cmd = ["npx", "-y", MCP_REMOTE, server["url"]]
        var = token_var(server)
        if var:
            header = server.get("header", "Authorization")
            child["AGATE_MCP_AUTH"] = server.get("token_prefix", "Bearer ") + env.get(var, "")
            cmd += ["--header", header + ":${AGATE_MCP_AUTH}"]
    exe = shutil.which(cmd[0], path=child.get("PATH")) or cmd[0]
    if os.name == "posix":
        os.execvpe(exe, [cmd[0]] + cmd[1:], child)
    return subprocess.call([exe] + cmd[1:], env=child)


def cmd_headers(root: Path, name: str, user: bool) -> int:
    server = get_server(root, name, user)
    var = token_var(server)
    if not var:
        print("{}")
        return 0
    value = secrets(root, user).get(var)
    if not value:
        print(f"Missing {var} in .env for '{name}'.", file=sys.stderr)
        print("{}")
        return 1
    print(json.dumps({server.get("header", "Authorization"): server.get("token_prefix", "Bearer ") + value}))
    return 0


def cmd_install(root: Path, name: str, harness: str, yes: bool, python: str) -> int:
    server = get_server(root, name)
    uhome = user_home()
    changes: list[str] = []

    # 1. Copy the script and the connector to ~/.config/agate (so it does not depend on this folder).
    user_servers = read_json(uhome / "servers.json", {"servers": {}})
    user_servers.setdefault("servers", {})[name] = server
    changes.append(f"{uhome / 'bin' / 'mcp.py'} ← copy of the Agate MCP tool (.agate/core/lib/mcp.py)")
    changes.append(f"{uhome / 'servers.json'} ← connector '{name}'")
    missing_vars = [v for v in server.get("env", []) if v not in dotenv_names(uhome / ".env")]
    if missing_vars:
        changes.append(f"{uhome / '.env'} ← empty lines: {', '.join(missing_vars)} (put your values there)")

    # 2. Register in the harness.
    entry = entry_for(harness, name, server, python, user=True)
    action = None
    if harness == "claude":
        command = ["claude", "mcp", "add-json", "--scope", "user", name, json.dumps(entry)]
        changes.append("command: " + " ".join(command[:-1]) + " '" + command[-1] + "'")

        def action():
            if not shutil.which("claude"):
                print("`claude` not found in PATH: run the command above by hand.")
                return
            subprocess.run(command, check=True)
    elif harness == "codex":
        path = Path(os.environ.get("CODEX_HOME") or home() / ".codex") / "config.toml"
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        block_text = current[current.index(CODEX_BEGIN):current.index(CODEX_END)] \
            if CODEX_BEGIN in current and CODEX_END in current else ""
        # The Agate block keeps the user-level connectors it already had and adds this one.
        keep = {n: entry_for("codex", n, s, python, user=True)
                for n, s in user_servers["servers"].items() if f"[mcp_servers.{n}]" in block_text or n == name}
        new = put_codex_block(current, codex_block(keep))
        changes.append(f"{path} ← block {CODEX_BEGIN} with [mcp_servers.{name}]:\n" + codex_block({name: entry}))

        def action():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(new, encoding="utf-8")
    elif harness == "gemini":
        path = home() / ".gemini" / "settings.json"
        changes.append(f"{path} ← mcpServers.{name} = {json.dumps(entry)}")

        def action():
            data = read_json(path)
            data.setdefault("mcpServers", {})[name] = entry
            write_json(path, data)
    elif harness == "opencode":
        base = home() / ".config" / "opencode"
        path = base / "opencode.json"
        snippet = {name: entry}
        if (base / "opencode.jsonc").is_file() and not path.is_file():
            changes.append(f"{base / 'opencode.jsonc'} has comments: not editing it. Add by hand under \"mcp\":\n"
                           + json.dumps(snippet, indent=2))
        else:
            changes.append(f"{path} ← mcp.{name} = {json.dumps(entry)}")

            def action():
                data = read_json(path)
                data.setdefault("$schema", "https://opencode.ai/config.json")
                data.setdefault("mcp", {})[name] = entry
                write_json(path, data)
    else:
        die(f"Unknown harness: {harness}")

    print(("Applying" if yes else "This is what would change (add --yes to apply it)") + f" — '{name}' at user level in {harness}:")
    for change in changes:
        print("  - " + change)
    if not yes:
        return 0
    (uhome / "bin").mkdir(parents=True, exist_ok=True)
    shutil.copy2(Path(__file__).resolve(), uhome / "bin" / "mcp.py")
    shutil.copy2(Path(__file__).resolve().parent / "project_extension.py", uhome / "bin" / "project_extension.py")
    write_json(uhome / "servers.json", user_servers)
    if missing_vars:
        dotenv = uhome / ".env"
        text = dotenv.read_text(encoding="utf-8") if dotenv.is_file() else "# User-level Agate tokens (not shared).\n"
        if not text.endswith("\n"):
            text += "\n"
        dotenv.write_text(text + f"# {name}\n" + "".join(f"{v}=\n" for v in missing_vars), encoding="utf-8")
        try:
            dotenv.chmod(0o600)
        except OSError:
            pass
    if action:
        action()
    print("Done. Restart the harness so it picks up the connector.")
    return 0


PASSTHROUGH = {"mcp": "project connectors (MCP): list, check, add, sync, doctor, hooks, extension, install"}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Project connectors (MCP) for any harness.")
    parser.add_argument("--project", default=str(ROOT), help="project root (default: this script's project)")
    parser.add_argument("--python", default="python3", help="Python command written into the configs "
                        "(on Windows it may be `py` or `python`)")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("list", help="connectors and whether their variables are set")
    p.add_argument("--user", action="store_true")
    p = sub.add_parser("check", help="compare .env with .env.example (without showing values)")
    p.add_argument("--strict", action="store_true", help="exit with code 1 if something required is missing")

    p = sub.add_parser("add", help="add a connector to servers.json, .env.example and .env")
    p.add_argument("name")
    p.add_argument("--type", choices=("local", "remote"), required=True)
    p.add_argument("--command")
    p.add_argument("--args", nargs=argparse.REMAINDER, default=[], help="local server arguments (must go last)")
    p.add_argument("--url")
    p.add_argument("--auth", choices=("oauth", "token", "none"), default="none")
    p.add_argument("--env", action="append", help="variable name it needs (repeatable)")
    p.add_argument("--token-env")
    p.add_argument("--docs")
    p.add_argument("--where", help="where to get the token (written as a comment in .env.example)")
    p.add_argument("--community", action="store_true", help="not official from the vendor (installed with confirmation)")
    p.add_argument("--by")
    p.add_argument("--force", action="store_true")

    p = sub.add_parser("sync", help="generate each harness config from servers.json")
    p.add_argument("--harness", default="all", choices=("all",) + HARNESSES)
    p.add_argument("--opencode-format", choices=("v1", "v2"))
    p.add_argument("--dry-run", action="store_true")
    p.add_argument("--if-stale", action="store_true", help="only if servers.json (or the extension) changed")
    p.add_argument("--quiet", action="store_true", help="print only notices that need attention")
    p.add_argument("--from-hook", action="store_true", help="(used by git hooks)")
    p.add_argument("--stage", action="store_true", help="`git add` the generated files (pre-commit hook)")

    p = sub.add_parser("doctor", help="diagnose a registered connector that does not answer")
    p.add_argument("name")
    p.add_argument("--harness", help="harness to check (default: detected)")
    p.add_argument("--timeout", type=float, default=30.0)

    p = sub.add_parser("hooks", help="git hooks that keep configs up to date")
    p.add_argument("action", choices=("install", "status"))

    p = sub.add_parser("extension", help=".agate/project/mcp.py: status, review, approve")
    p.add_argument("action", choices=("status", "review", "approve"))

    p = sub.add_parser("run", help="(used by harnesses)")
    p.add_argument("name")
    p.add_argument("--user", action="store_true")
    p.add_argument("--test", action="store_true", help="start it and check it answers, then stop")
    p.add_argument("--timeout", type=float, default=30.0)
    p = sub.add_parser("headers", help="(used by harnesses)")
    p.add_argument("name")
    p.add_argument("--user", action="store_true")

    p = sub.add_parser("install", help="register a project connector at user level in a harness")
    p.add_argument("name")
    p.add_argument("--scope", choices=("user",), default="user")
    p.add_argument("--harness", choices=HARNESSES, required=True)
    p.add_argument("--yes", action="store_true", help="apply (without it, only shows what would change)")

    a = parser.parse_args(argv)
    root = Path(a.project).resolve()
    if a.cmd == "list":
        return cmd_list(root, a.user)
    if a.cmd == "check":
        return cmd_check(root, a.strict)
    if a.cmd == "add":
        return cmd_add(root, a)
    if a.cmd == "sync":
        if a.if_stale and not is_stale(root):
            return 0
        harnesses = list(HARNESSES) if a.harness == "all" else [a.harness]
        report = sync(root, harnesses, a.python, a.opencode_format, a.dry_run)
        prefix = "Agate (git hook): " if a.from_hook else ""
        if not a.quiet:
            print(("Dry run: " if a.dry_run else "") + "configs generated: " + (", ".join(report["written"]) or "none"))
            if report["skipped"]:
                print("Unchanged or not editable: " + ", ".join(report["skipped"]))
        elif report["written"] and a.from_hook:
            print(prefix + "MCP configs regenerated (" + ", ".join(report["written"]) + "). Open a new chat to use them.")
        for note in report["notes"]:
            if a.quiet and note.startswith("Codex only reads"):
                continue
            print(prefix + "! " + note)
        if a.stage and not a.dry_run:
            files = [f for f in generated_files(root) if (root / f).exists()]
            if files:
                _git(root, "add", "--", *files)
        return 0
    if a.cmd == "doctor":
        return cmd_doctor(root, a.name, a.harness, a.timeout)
    if a.cmd == "hooks":
        return cmd_hooks(root, a.action)
    if a.cmd == "extension":
        return cmd_extension(root, a.action)
    if a.cmd == "run":
        if a.test:
            ok, detail = probe_server(root, a.name, a.timeout)
            print(("OK: " if ok else "FAILED: ") + detail)
            return 0 if ok else 1
        return cmd_run(root, a.name, a.user)
    if a.cmd == "headers":
        return cmd_headers(root, a.name, a.user)
    if a.cmd == "install":
        return cmd_install(root, a.name, a.harness, a.yes, a.python)
    return 1


if __name__ == "__main__":
    sys.exit(main())
