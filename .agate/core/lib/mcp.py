# ---------------------------------------------------------------- helpers

def user_home() -> Path:
    """User-level Agate folder (global tokens and connectors)."""
    return Path(os.environ.get("AGATE_HOME") or Path.home() / ".config" / "agate").expanduser()


def home() -> Path:
    return Path(os.environ.get("HOME") or Path.home()).expanduser()


def die(message: str, code: int = 2) -> None:
    print(f"Error: {message}", file=sys.stderr)
    raise SystemExit(code)


def read_json(path: Path, default=None):
    if not path.is_file():
        return {} if default is None else default
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        die(f"{path} is not valid JSON ({exc}). Leaving it untouched.")


def write_json(path: Path, data) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def parse_dotenv(path: Path) -> dict[str, str]:
    """KEY=VALUE per line; ignores comments and `export `; strips quotes. Never printed."""
    values: dict[str, str] = {}
    if not path.is_file():
        return values
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        if line.startswith("export "):
            line = line[7:].lstrip()
        key, _, value = line.partition("=")
        key, value = key.strip(), value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        elif " #" in value:
            value = value.split(" #", 1)[0].rstrip()
        if VAR_RE.match(key):
            values[key] = value
    return values


def dotenv_names(path: Path) -> list[str]:
    """Variable names (with or without value) that appear in a .env-style file."""
    if not path.is_file():
        return []
    names = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line.startswith("export "):
            line = line[7:]
        match = re.match(r"([A-Z][A-Z0-9_]*)\s*=", line)
        if match and match.group(1) not in names:
            names.append(match.group(1))
    return names


def secrets(root: Path, user: bool) -> dict[str, str]:
    """Available values: environment < ~/.config/agate/.env < project .env (closest wins)."""
    merged = dict(os.environ)
    merged.update({k: v for k, v in parse_dotenv(user_home() / ".env").items() if v})
    if not user:
        merged.update({k: v for k, v in parse_dotenv(root / ".env").items() if v})
    return merged


def servers_path(root: Path, user: bool) -> Path:
    return user_home() / "servers.json" if user else root / SERVERS_REL


def load_servers(root: Path, user: bool = False) -> dict:
    return read_json(servers_path(root, user), {"servers": {}}).get("servers", {})


def get_server(root: Path, name: str, user: bool = False) -> dict:
    servers = load_servers(root, user)
    if name not in servers:
        where = "~/.config/agate/servers.json" if user else str(SERVERS_REL)
        die(f"No connector '{name}' in {where}. See `agate.py mcp list`.")
    return servers[name]


def token_var(server: dict) -> str | None:
    if server.get("auth") != "token":
        return None
    return server.get("token_env") or (server.get("env") or [None])[0]


def expand(value: str, env: dict[str, str], allowed: list[str]) -> str:
    """Replace ${VAR} only with declared variables."""
    def sub(match):
        var = match.group(1)
        return env.get(var, "") if var in allowed else match.group(0)
    return re.sub(r"\$\{([A-Z][A-Z0-9_]*)\}", sub, value)


# ---------------------------------------------------------------- per-harness generation

def script_ref(harness: str, user: bool) -> str:
    """Script path as written in each harness config (relative at project level, absolute at user level)."""
    if user:
        return str(user_home() / "bin" / "mcp.py")
    if harness == "claude":
        # Claude Code expands ${CLAUDE_PROJECT_DIR:-.} in command/args of .mcp.json.
        return "${CLAUDE_PROJECT_DIR:-.}/" + SCRIPT_REL
    return SCRIPT_REL


def wrapper(harness: str, name: str, python: str, user: bool, verb: str = "run") -> tuple[str, list[str]]:
    if user:
        args = [script_ref(harness, user), verb, name, "--user"]
    else:
        args = [script_ref(harness, user), "mcp", verb, name]
    return python, args


def headers_cmd(harness: str, name: str, python: str, user: bool) -> str:
    cmd, args = wrapper(harness, name, python, user, verb="headers")
    path = args[0].replace("${CLAUDE_PROJECT_DIR:-.}/", "")  # the helper already runs in the project folder
    return " ".join([cmd, path] + args[1:])


def entry_for(harness: str, name: str, server: dict, python: str, user: bool = False, opencode_v2: bool = False):
    """Return the config entry for that harness (a dict; for Codex, a dict later rendered as TOML)."""
    kind, auth = server.get("type"), server.get("auth", "none")
    remote_direct = kind == "remote" and auth in ("oauth", "none")
    remote_token = kind == "remote" and auth == "token"
    url = server.get("url", "")

    if harness == "claude":
        if remote_direct:
            return {"type": "http", "url": url}
        if remote_token:
            return {"type": "http", "url": url, "headersHelper": headers_cmd(harness, name, python, user)}
        cmd, args = wrapper(harness, name, python, user)
        return {"type": "stdio", "command": cmd, "args": args}

    if harness == "codex":
        if remote_direct:
            return {"url": url}
        if remote_token:
            return {"url": url, "http_headers_helper": headers_cmd(harness, name, python, user)}
        cmd, args = wrapper(harness, name, python, user)
        return {"command": cmd, "args": args}

    if harness == "gemini":
        if remote_direct:
            return {"httpUrl": url}
        cmd, args = wrapper(harness, name, python, user)  # local, or remote with a token (via proxy)
        return {"command": cmd, "args": args}

    if harness == "opencode":
        if remote_direct:
            entry = {"type": "remote", "url": url}
        else:
            cmd, args = wrapper(harness, name, python, user)
            entry = {"type": "local", "command": [cmd] + args}
        if not opencode_v2:
            entry["enabled"] = True
        return entry

    raise ValueError(harness)


def toml_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    return json.dumps(str(value), ensure_ascii=False)  # TOML basic strings: same escaping as JSON


def codex_block(entries: dict[str, dict]) -> str:
    lines = [CODEX_BEGIN, "# Generated by `.agate/agate.py mcp sync` from .agate/mcp/servers.json. Do not edit by hand."]
    for name, entry in entries.items():
        key = name if re.match(r"^[A-Za-z0-9_-]+$", name) else json.dumps(name)
        lines.append(f"[mcp_servers.{key}]")
        for k, v in entry.items():
            lines.append(f"{k} = {toml_value(v)}")
        lines.append("")
    lines.append(CODEX_END)
    return "\n".join(lines) + "\n"


def put_codex_block(text: str, block: str) -> str:
    if CODEX_BEGIN in text and CODEX_END in text:
        start = text.index(CODEX_BEGIN)
        end = text.index(CODEX_END, start) + len(CODEX_END)
        rest = text[end:]
        return text[:start] + block.rstrip("\n") + (rest if rest.startswith("\n") else "\n" + rest)
    sep = "" if not text or text.endswith("\n\n") else ("\n" if text.endswith("\n") else "\n\n")
    return text + sep + block


def opencode_is_v2(root: Path, explicit: str | None) -> bool:
    if explicit:
        return explicit == "v2"
    existing = read_json(root / "opencode.json")
    if isinstance(existing.get("mcp"), dict) and isinstance(existing["mcp"].get("servers"), dict):
        return True
    exe = shutil.which("opencode")
    if exe:
        try:
            out = subprocess.run([exe, "--version"], capture_output=True, text=True, timeout=10).stdout
            match = re.search(r"(\d+)\.", out)
            if match:
                return int(match.group(1)) >= 2
        except (OSError, subprocess.SubprocessError):
            pass
    return False


def merge_servers(container: dict, path: list[str], entries: dict, previous: list[str]) -> dict:
    """Insert `entries` into container[path…], removing what we generated before and is gone. Leaves others' entries alone."""
    node = container
    for key in path:
        node = node.setdefault(key, {})
    for name in previous:
        if name not in entries:
            node.pop(name, None)
    node.update(entries)
    return container


# ---------------------------------------------------------------- fingerprint (staleness)

def fingerprint(root: Path) -> dict:
    """What the generated configs depend on: servers.json and the project extension (if any)."""
    servers = root / SERVERS_REL
    return {"servers": hashlib.sha256(servers.read_bytes()).hexdigest() if servers.is_file() else None,
            "extension": px.file_hash(px.extension_path(root, "mcp"))}


def is_stale(root: Path) -> bool:
    generated = read_json(root / GENERATED_REL, {})
    stored = generated.get(HASHES_KEY)
    if stored is None:
        # Never synced with a fingerprint: stale only if there is something to generate.
        return bool(load_servers(root)) or any(k for k in generated if k != HASHES_KEY) \
            or px.extension_path(root, "mcp").is_file()
    return stored != fingerprint(root)


# ---------------------------------------------------------------- project extension (Template Method)

def project_extension(root: Path):
    """(module or None, status). Never returns an unapproved extension."""
    this = sys.modules.get(__name__)
    if this is None:  # loaded by path without registering (tests, other tools): expose our globals instead
        import types
        this = types.SimpleNamespace(**globals())
    return px.load_project_extension(root, "mcp", inject={"mcp": this})


def extension_harnesses(ext) -> list:
    return list(getattr(ext, "HARNESSES", []) or []) if ext else []


def sync_extension_harness(root: Path, adapter, servers: dict, previous_file: str | None, dry_run: bool) -> str:
    """Write one harness defined by the project extension. Returns the relative (or absolute) path written."""
    path = Path(adapter.config_path(root))
    target = path if path.is_absolute() else root / path
    existing = target.read_text(encoding="utf-8") if target.is_file() else ""
    rendered = adapter.render(servers)
    new = adapter.merge(existing, rendered) if hasattr(adapter, "merge") else rendered
    if not dry_run:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(new, encoding="utf-8")
    try:
        return target.relative_to(root).as_posix()
    except ValueError:
        return str(target)


def sync(root: Path, harnesses: list[str], python: str = "python3", opencode_format: str | None = None,
         dry_run: bool = False, use_extension: bool = True) -> dict:
    servers = load_servers(root)
    generated = read_json(root / GENERATED_REL, {})
    report = {"written": [], "skipped": [], "notes": [], "extension": "absent"}
    ext = None
    if use_extension:
        ext, report["extension"] = project_extension(root)
        if report["extension"] == "unapproved":
            report["notes"].append(".agate/project/mcp.py changed (by someone else) and is not approved yet: generated "
                                   "only the built-in harnesses. Review it: `agate.py mcp extension review`, then "
                                   "`agate.py mcp extension approve`.")
    if ext and hasattr(ext, "before_sync"):
        servers = ext.before_sync(dict(servers)) or servers
    for harness in harnesses:
        previous = generated.get(harness, {}).get("servers", [])
        if harness == "opencode":
            v2 = opencode_is_v2(root, opencode_format)
            entries = {n: entry_for(harness, n, s, python, opencode_v2=v2) for n, s in servers.items()}
            if (root / "opencode.jsonc").is_file() and not (root / "opencode.json").is_file():
                report["skipped"].append("opencode.jsonc")
                report["notes"].append("OpenCode uses opencode.jsonc (with comments): not editing it. Copy by hand:\n"
                                       + json.dumps({"mcp": {"servers": entries} if v2 else entries}, indent=2))
                continue
            rel, data = "opencode.json", read_json(root / "opencode.json")
            data.setdefault("$schema", "https://opencode.ai/config.json")
            merge_servers(data, ["mcp", "servers"] if v2 else ["mcp"], entries, previous)
        elif harness == "claude":
            entries = {n: entry_for(harness, n, s, python) for n, s in servers.items()}
            rel, data = ".mcp.json", read_json(root / ".mcp.json")
            merge_servers(data, ["mcpServers"], entries, previous)
        elif harness == "gemini":
            entries = {n: entry_for(harness, n, s, python) for n, s in servers.items()}
            rel, data = ".gemini/settings.json", read_json(root / ".gemini/settings.json")
            merge_servers(data, ["mcpServers"], entries, previous)
        elif harness == "codex":
            entries = {n: entry_for(harness, n, s, python) for n, s in servers.items()}
            rel = ".codex/config.toml"
            if not servers and not previous and not (root / rel).is_file():
                report["skipped"].append(rel)
                continue
            current = (root / rel).read_text(encoding="utf-8") if (root / rel).is_file() else ""
            new = put_codex_block(current, codex_block(entries))
            if not dry_run:
                (root / rel).parent.mkdir(parents=True, exist_ok=True)
                (root / rel).write_text(new, encoding="utf-8")
            report["written"].append(rel)
            report["notes"].append("Codex only reads .codex/config.toml in projects marked as trusted.")
            generated[harness] = {"file": rel, "servers": sorted(entries)}
            continue
        else:
            die(f"Unknown harness: {harness}")
        if not servers and not previous and not (root / rel).is_file():
            report["skipped"].append(rel)  # nothing to write: no empty files created
            continue
        if not dry_run:
            write_json(root / rel, data)
        report["written"].append(rel)
        generated[harness] = {"file": rel, "servers": sorted(entries)}
    for adapter in extension_harnesses(ext):
        name = getattr(adapter, "name", None) or type(adapter).__name__.lower()
        if not servers and name not in generated:
            continue
        rel = sync_extension_harness(root, adapter, servers, generated.get(name, {}).get("file"), dry_run)
        report["written"].append(rel)
        generated[name] = {"file": rel, "servers": sorted(servers), "extension": True}
    if not dry_run and (any(k for k in generated if k != HASHES_KEY) or (root / GENERATED_REL).is_file()):
        stamp = fingerprint(root)
        if report["extension"] == "unapproved":
            stamp["extension"] = None  # stays stale until the extension is approved and synced
        generated[HASHES_KEY] = stamp
        write_json(root / GENERATED_REL, generated)
    if ext and hasattr(ext, "after_sync"):
        ext.after_sync(report)
    return report


def generated_files(root: Path) -> list[str]:
    """Generated config files inside the project (for `git add` from the pre-commit hook)."""
    generated = read_json(root / GENERATED_REL, {})
    files = [str(GENERATED_REL.as_posix())]
    for key, value in generated.items():
        if key != HASHES_KEY and isinstance(value, dict) and value.get("file"):
            if not Path(value["file"]).is_absolute() and (root / value["file"]).is_file():
                files.append(value["file"])
    return sorted(set(files))


# ---------------------------------------------------------------- commands

def cmd_list(root: Path, user: bool) -> int:
    servers = load_servers(root, user)
    if not servers:
        print("No connectors in " + ("~/.config/agate/servers.json." if user else ".agate/mcp/servers.json.")
              + " To add one, see .agate/core/guides/mcp-add.md.")
        return 0
    env = secrets(root, user)
    for name, s in sorted(servers.items()):
        status = []
        for var in s.get("env", []):
            status.append(f"{var} {'ok' if env.get(var) else 'MISSING'}")
        origin = "official" if s.get("official") else "community"
        target = s.get("url") or " ".join([s.get("command", "")] + list(s.get("args", [])))
        print(f"- {name} · {s.get('type')} · auth {s.get('auth', 'none')} · {origin} · {target}")
        if status:
            print("    variables: " + ", ".join(status))
    return 0


def cmd_check(root: Path, strict: bool) -> int:
    example = dotenv_names(root / ".env.example")
    values = parse_dotenv(root / ".env")
    present = set(dotenv_names(root / ".env"))
    declared = []
    for name, s in load_servers(root).items():
        for var in s.get("env", []):
            declared.append((var, name))
    missing = [v for v in example if v not in present]
    empty = [v for v in example if v in present and not values.get(v)]
    needed = [(v, n) for v, n in declared if not values.get(v) and not os.environ.get(v)]
    not_in_example = sorted({v for v, _ in declared if v not in example})

    if not (root / ".env").is_file():
        print("No .env yet: create it by copying .env.example (the agent can do it).")
    if missing:
        print("Missing from your .env (listed in .env.example): " + ", ".join(missing))
    if empty:
        print("Empty in your .env (they may be optional): " + ", ".join(empty))
    if needed:
        print("Connectors without their token: " + ", ".join(f"{n} → {v}" for v, n in needed))
    if not_in_example:
        print("Variables in servers.json that are not in .env.example: " + ", ".join(not_in_example))
    stale = is_stale(root)
    if stale:
        print("MCP config out of date: run `python3 .agate/agate.py mcp sync --if-stale`.")
    ext_state = px.status(root, "mcp")
    if ext_state == "unapproved":
        print(".agate/project/mcp.py changed (by someone else) and is not approved: "
              "`agate.py mcp extension review`, then `agate.py mcp extension approve` with the person's ok.")
    hooks = hooks_state(root)
    if hooks == "inactive":
        print("Git hooks are not active (they keep MCP configs up to date after pulls): "
              "`python3 .agate/agate.py mcp hooks install`.")
    if not (missing or empty or needed or not_in_example or stale or ext_state == "unapproved"
            or hooks == "inactive"):
        print("All good: .env has every variable from .env.example and the MCP config is up to date.")
    return 1 if strict and (missing or needed) else 0


# ---------------------------------------------------------------- git hooks

def _git(root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True)


def hooks_state(root: Path) -> str:
    """'active', 'inactive' or 'no-git' (also 'missing' if the hook files are not in the project)."""
    if _git(root, "rev-parse", "--is-inside-work-tree").stdout.strip() != "true":
        return "no-git"
    if not (root / HOOKS_REL).is_dir():
        return "missing"
    current = _git(root, "config", "--get", "core.hooksPath").stdout.strip()
    return "active" if current.rstrip("/") == HOOKS_REL else "inactive"


def cmd_hooks(root: Path, action: str) -> int:
    state = hooks_state(root)
    if action == "status":
        print({"active": f"Git hooks active ({HOOKS_REL}).",
               "inactive": "Git hooks not active. Run `python3 .agate/agate.py mcp hooks install`.",
               "missing": f"No {HOOKS_REL}/ in this project (sync the base).",
               "no-git": "Not a git repository: hooks do not apply."}[state])
        return 0 if state in ("active", "no-git") else 1
    if state == "no-git":
        print("Not a git repository: hooks do not apply.")
        return 0
    if state == "missing":
        die(f"No {HOOKS_REL}/ in this project. Sync the base first (`agate.py update`).")
    previous = _git(root, "config", "--get", "core.hooksPath").stdout.strip()
    if previous and previous.rstrip("/") != HOOKS_REL:
        print(f"Note: core.hooksPath was '{previous}'. Hooks there stop running; move them to {HOOKS_REL}/ if needed.")
    for hook in (root / HOOKS_REL).iterdir():
        if hook.is_file():
            try:
                hook.chmod(hook.stat().st_mode | 0o111)
            except OSError:
                pass
    _git(root, "config", "core.hooksPath", HOOKS_REL)
    print(f"Git hooks active ({HOOKS_REL}): MCP configs regenerate after pulls, checkouts and rebases, "
          "and before commits that change .agate/mcp/servers.json.")
    return 0


# ---------------------------------------------------------------- doctor

def current_harness() -> str | None:
    """Best guess of the harness running this command (from its environment variables)."""
    env = os.environ
    if env.get("CLAUDECODE"):
        return "claude"
    if env.get("GEMINI_CLI"):
        return "gemini"
    if any(k.startswith("OPENCODE") for k in env):
        return "opencode"
    if any(k.startswith("CODEX_") and k != "CODEX_HOME" for k in env):
        return "codex"
    return None


def probe_server(root: Path, name: str, timeout: float = 30.0) -> tuple[bool, str]:
    """Start the connector and check it answers: MCP `initialize` over stdio, or HTTP reachability if remote."""
    server = get_server(root, name)
    env = secrets(root, False)
    child, missing = build_env(server, env)
    if missing:
        return False, "missing values in .env: " + ", ".join(missing)
    init = {"jsonrpc": "2.0", "id": 1, "method": "initialize",
            "params": {"protocolVersion": "2025-06-18", "capabilities": {},
                       "clientInfo": {"name": "agate-doctor", "version": "1"}}}
    if server.get("type") == "remote":
        headers = {"Content-Type": "application/json", "Accept": "application/json, text/event-stream"}
        var = token_var(server)
        if var:
            headers[server.get("header", "Authorization")] = server.get("token_prefix", "Bearer ") + env.get(var, "")
        request = urllib.request.Request(server["url"], data=json.dumps(init).encode(), headers=headers)
        try:
            with urllib.request.urlopen(request, timeout=timeout) as response:
                return True, f"reachable (HTTP {response.status})"
        except urllib.error.HTTPError as exc:
            if exc.code in (401, 403):
                hint = "sign in from the harness (OAuth)" if server.get("auth") == "oauth" else "check the token"
                return exc.code == 401 and server.get("auth") == "oauth", f"HTTP {exc.code}: {hint}"
            return False, f"HTTP {exc.code}"
        except (urllib.error.URLError, OSError) as exc:
            return False, f"not reachable ({getattr(exc, 'reason', exc)})"
    declared = list(server.get("env", []))
    cmd = [expand(server["command"], env, declared)] + [expand(x, env, declared) for x in server.get("args", [])]
    exe = shutil.which(cmd[0], path=child.get("PATH")) or cmd[0]
    try:
        proc = subprocess.Popen([exe] + cmd[1:], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                stderr=subprocess.DEVNULL, env=child, cwd=str(root), text=True)
    except OSError as exc:
        return False, f"could not start '{cmd[0]}' ({exc})"
    try:
        proc.stdin.write(json.dumps(init) + "\n")
        proc.stdin.flush()
        deadline = time.time() + timeout

        sel = selectors.DefaultSelector()
        try:
            sel.register(proc.stdout, selectors.EVENT_READ)
            use_select = True
        except (ValueError, OSError):
            use_select = False  # Windows pipes: fall back to a blocking read
        while time.time() < deadline:
            if use_select and not sel.select(timeout=max(0.0, deadline - time.time())):
                break
            line = proc.stdout.readline()
            if not line:
                break
            try:
                message = json.loads(line)
            except json.JSONDecodeError:
                continue
            if isinstance(message, dict) and message.get("id") == 1:
                if "result" in message:
                    info = message["result"].get("serverInfo", {})
                    return True, f"answered initialize ({info.get('name', 'server')} {info.get('version', '')})".strip()
                return False, f"error on initialize: {message.get('error')}"
        return False, f"no answer to initialize within {int(timeout)} s"
    finally:
        proc.kill()
        try:
            proc.wait(timeout=5)
        except subprocess.SubprocessError:
            pass
        for stream in (proc.stdin, proc.stdout):
            try:
                stream.close()
            except (OSError, ValueError):
                pass


def cmd_doctor(root: Path, name: str, harness: str | None, timeout: float) -> int:
    server = get_server(root, name)
    ext, ext_state = project_extension(root)
    known = list(HARNESSES) + [getattr(a, "name", "") for a in extension_harnesses(ext)]
    if harness is None:
        harness = current_harness()
        for adapter in extension_harnesses(ext):
            if harness is None and hasattr(adapter, "detect") and adapter.detect():
                harness = getattr(adapter, "name", None)
    problems = 0

    def line(ok: bool | None, text: str) -> None:
        nonlocal problems
        mark = {True: "[ok]", False: "[!!]", None: "[--]"}[ok]
        problems += ok is False
        print(f"{mark} {text}")

    print(f"Doctor for '{name}' ({server.get('type')}, auth {server.get('auth', 'none')}) · harness: "
          f"{harness or 'unknown'}")
    if ext_state == "unapproved":
        line(False, ".agate/project/mcp.py is not approved: its harnesses and checks are skipped "
                    "(`agate.py mcp extension review` / `approve`).")
    # 1. config generated for this harness
    generated = read_json(root / GENERATED_REL, {})
    if is_stale(root):
        line(False, "MCP config out of date: run `agate.py mcp sync --if-stale`, then open a new chat.")
    if harness in known:
        entry = generated.get(harness, {})
        if name in entry.get("servers", []):
            line(True, f"config generated for {harness} ({entry.get('file')})")
        else:
            line(False, f"no config for {harness} yet: run `agate.py mcp sync`.")
    else:
        line(None, "harness not recognized: Agate generates configs for "
                   + ", ".join(known) + ". See 'Unknown harness' below.")
    # 2. token
    env = secrets(root, False)
    missing = [v for v in server.get("env", []) if not env.get(v)]
    if missing:
        line(False, "missing in .env: " + ", ".join(missing) + " (ask the person to paste it in .env, not in the chat)")
    else:
        line(True, "variables present" if server.get("env") else "no variables needed")
    # 3. server starts / answers
    if not missing:
        ok, detail = probe_server(root, name, timeout)
        line(ok, ("server: " + detail))
    # 4. extension checks
    if ext and hasattr(ext, "doctor_checks"):
        for text in ext.doctor_checks(name) or []:
            line(None, text)
    # 5. reminders
    print("\nRemember:")
    print("- Harnesses load MCP servers when a chat starts: after `sync`, open a new chat (in Claude Code, `/mcp` "
          "can reconnect).")
    print("- Claude Code asks to approve the project's servers (.mcp.json) the first time; Codex only reads "
          ".codex/config.toml in trusted projects.")
    if harness not in known:
        print("\nUnknown harness:")
        print("1. Read that harness's official docs on MCP configuration (web-research).")
        print("2. Write .agate/project/mcp.py with a harness adapter (name, detect, config_path, render, merge); see "
              ".agate/core/guides/mcp-extend.md. Then `agate.py mcp sync`.")
        print("3. Tell the person what you did, and suggest adding that harness to Agate itself.")
    return 1 if problems else 0


