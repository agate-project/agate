#!/usr/bin/env python3
"""Project connectors (MCP): a single list (`.agate/mcp/servers.json`) for every harness.

Usage (from the project root; the agent runs it):
    python3 .agate/agate.py mcp list
    python3 .agate/agate.py mcp check [--strict]
    python3 .agate/agate.py mcp add <name> --type local --command npx --args -y package@1.2.3 --env VAR --where "…"
    python3 .agate/agate.py mcp add <name> --type remote --url https://… --auth oauth|token|none [--env VAR]
    python3 .agate/agate.py mcp sync [--harness all|…] [--if-stale] [--quiet]
    python3 .agate/agate.py mcp doctor <name> [--harness X]  # a registered connector does not answer: why?
    python3 .agate/agate.py mcp hooks install|status         # git hooks that keep configs up to date
    python3 .agate/agate.py mcp extension status|review|approve   # .agate/project/mcp.py (project extension)
    python3 .agate/agate.py mcp run <name> [--user] [--test] # called by harnesses, not by people
    python3 .agate/agate.py mcp headers <name> [--user]      # same: headers for remote servers with a token
    python3 .agate/agate.py mcp install <name> --scope user --harness claude|codex|gemini|opencode [--yes]

Rules:
- Secret values live in `.env` (each person's own, not committed) or in `~/.config/agate/.env` (user level).
  This script never prints them, except `headers`, which exists to hand them to the harness that asks.
- Files generated by `sync` carry no secrets: local servers start through `agate.py mcp run`, which reads `.env` and
  passes only the variables declared in `servers.json`.
- `sync` always generates for every supported harness (deterministic output, safe to commit) and records a
  fingerprint of `servers.json` (and of the project extension) so `check` and `sync --if-stale` know when the
  generated configs are out of date. Git hooks in `.agate/hooks/` run `sync --if-stale` after pulls and checkouts.
- A project may extend this tool with `.agate/project/mcp.py` (extra harnesses, hooks around `sync`, extra doctor
  checks). It only runs once approved; see `project_extension.py`.
"""
